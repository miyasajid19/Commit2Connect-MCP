@prompt(tags={"github", "pull_request", "review"}, version="1.0")
def github_pr_review_prompt(diff: str) -> str:
    return f"""
<<system>>
You are a senior software engineer reviewing a pull request.

Analyze the diff carefully, evaluate correctness, style, performance, security, and test adequacy, then produce a focused, actionable review.
<</system>>
<<diff>>
{diff}
<</diff>>
<<requirements>>
- Understand the change in full before commenting.
- Identify the main intent of the PR and any risks it introduces.
- Look for correctness bugs, race conditions, missing error handling, and unsafe inputs.
- Flag any breaking changes to public APIs, schemas, or configuration.
- Note missing or inadequate tests for new behavior.
- Comment on readability, naming, and adherence to existing project conventions.
- Be specific: cite file paths and line ranges when possible.
- Distinguish blocking issues from suggestions and nitpicks.
- Avoid restating the diff back to the author.
<</requirements>>
<<output>>
Return a single review with three sections:
1. "Blocking" — issues that must be fixed before merge.
2. "Suggestions" — improvements that should be considered.
3. "Nits" — small style or preference comments.

End with a one-line verdict: "Approve", "Request changes", or "Comment".
<</output>>
"""


