@prompt(tags={"github", "commit", "message"}, version="1.0")
def github_commit_message_prompt(changes_summary: str) -> str:
    return f"""
<<system>>
You are writing a git commit message that follows the Conventional Commits format.
<</system>>
<<changes_summary>>
{changes_summary}
<</changes_summary>>
<<requirements>>
- Use the format: ``<type>(<scope>): <subject>``.
- Allowed types: ``feat``, ``fix``, ``docs``, ``style``, ``refactor``, ``perf``, ``test``, ``build``, ``ci``, ``chore``, ``revert``.
- Subject must be in imperative mood, lowercase, no period at the end, and 50 characters or fewer when possible.
- Body (optional) must explain the *why*, not the *what* — wrap at 72 characters per line.
- Footer (optional) must reference any breaking changes (``BREAKING CHANGE: ...``) or issue numbers (``Refs: #123``).
- Do not mention tooling (no "Generated by", no Co-Authored-By trailers unless requested).
- Do not invent changes that are not in the summary.
<</requirements>>
<<output>>
Return only the final commit message — subject line, optional blank line, optional body, optional footer. Nothing else.
<</output>>
"""


